def centimetrosApulgadas(cm):
    pulgadas = cm / 2.54
    return pulgadas


def pulgadasAcentimetros(pulgadas):
    cm = pulgadas * 2.54
    return cm
    
def kilometrosAmillas(km):
    millas = km / 1.609344
    return millas


def millasAkilometros(millas):
    km = millas * 1.609344
    return km
